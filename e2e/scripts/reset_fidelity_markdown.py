"""
reset_fidelity_markdown.py - Render docs/RESET_FIDELITY.md from a measured
                             ResetFidelityReport (EVAL-P12.1).

Layer: e2e tooling. Presentation only — it computes no verdict of its own.

Split out of measure_reset_fidelity.py to keep both under the 300-line cap, and
because a renderer that could decide anything would be a second place the tier
could be softened. It receives a report and formats it.

Usage: imported by e2e/scripts/measure_reset_fidelity.py.
"""

from __future__ import annotations

from typing import Any, Sequence

# Verdict wording comes from EVAL-P12.1: every surviving item is judged either
# harmless or as a reason the k repetitions are not independent.
_VERDICT_CORRELATES = "**correlates repeats**"
_VERDICT_UNKNOWN = "**correlates repeats (unproven)**"


def _verdict(component: str) -> str:
    """Return the verdict cell for one surviving component."""
    if component.startswith("unknown:"):
        return _VERDICT_UNKNOWN
    return _VERDICT_CORRELATES


def _surviving_rows(report: Any) -> str:
    rows = [
        f"| `{c}` | observed | {_verdict(c)} |" for c in report.observed_surviving
    ]
    rows += [
        f"| `{name}` | **not observable** | {_VERDICT_UNKNOWN} |"
        for name in report.unobservable
    ]
    return "\n".join(rows) or "| _(nothing)_ | — | — |"


def _cleared_rows(report: Any) -> str:
    rows = [f"| `{c}` | restored to its pre-scenario value | acceptable |" for c in report.cleared]
    return "\n".join(rows) or "| _(nothing)_ | — | — |"


def _unobservable_rows(stores: Sequence[tuple[str, str]]) -> str:
    return "\n".join(f"| `{name}` | {reason} |" for name, reason in stores)


def render(
    report: Any,
    applied: Sequence[str],
    costs: Sequence[int],
    component_count: int,
    unobservable_stores: Sequence[tuple[str, str]],
) -> str:
    """Render the fidelity report as Markdown.

    Args:
        report: The measured ResetFidelityReport.
        applied: Mutations the scenario actually applied.
        costs: Per-reset wall-clock costs in ms.
        component_count: How many components the snapshot covered.
        unobservable_stores: (store, reason) pairs the API cannot read.
    Returns:
        The document text.
    """
    ordered = sorted(costs)
    return f"""# Reset fidelity — what `preconditions.reset_world` actually clears

**Measured:** {report.measured_at}
**Commit:** `{report.git_sha}`
**Verdict:** **{report.fidelity}**
**Machine-readable artifact:** [`evals/reset_fidelity.json`](../evals/reset_fidelity.json)

> Generated by `e2e/scripts/measure_reset_fidelity.py`. Do not hand-edit — re-run it.

## Verdict

`reset_world` is **{report.fidelity}**. Under `docs/SEQUENCE_STATS_POLICY.md` §2 there are
exactly two tiers and **FULL requires that nothing survives**. {_verdict_sentence(report)}

The tier is not a judgement call in this pipeline: `evals/reset_fidelity_record.py` derives it
from `surviving` and refuses to construct a report whose declared tier contradicts the evidence,
in either direction.

## Method

Snapshotted **{component_count} components** (every node type, every edge type, the emotion store,
the game clock and the engine-status store), ran a mutating scenario, called `reset_world`, and
snapshotted again. A component counts as **cleared** only if the scenario changed it *and* it
returned to its pre-scenario digest. Components the scenario never touched prove nothing either
way and appear in neither table.

Mutations applied:

{chr(10).join(f'- `{m}`' for m in applied)}

## What survived

⚠️ **This table is a LOWER BOUND, not an inventory.** A component only appears here if this
particular scenario happened to change it. A store the scenario never touched is absent from both
tables and is *not* thereby shown to be cleared — `reset_world` PATCHes two world_state properties
and nothing else, so every other component in the engine survives it by construction; this run
proves it for the ones it exercised. Read the rows below as "at least these".

| Component | How it was determined | Verdict |
|---|---|---|
{_surviving_rows(report)}

## What was cleared

| Component | Evidence | Verdict |
|---|---|---|
{_cleared_rows(report)}

## What could not be observed at all

These are in-process singletons from `src/npc_engine/api/dependencies_stores.py` with no read
endpoint. They are listed in `surviving` as `unknown:<name>` rather than omitted. **An
unobservable store is not an absent one** — silently dropping one is exactly how a PARTIAL reset
gets written up as a FULL one.

| Store | Why it cannot be read over HTTP |
|---|---|
{_unobservable_rows(unobservable_stores)}

## Per-reset cost

Measured over **{len(costs)}** consecutive resets: `{list(costs)}` ms.

- **median {report.duration_ms} ms** ← the number `evals/reset_fidelity.json` publishes
- min {ordered[0]} ms, max {ordered[-1]} ms

EVAL-P12.4's wall-clock budget is `6 scenarios x k x (turns + reset_cost)`, computed from the
median above.

## Consequences

{_consequences(report)}
"""


def _verdict_sentence(report: Any) -> str:
    """One sentence stating why the tier came out as it did."""
    if report.fidelity == "FULL":
        return "Nothing survived the reset and every store was observable."
    observed = len(report.observed_surviving)
    unknown = len(report.unobservable)
    return (
        f"**{observed} observed component(s) survived it**, and **{unknown} store(s) could not be "
        f"observed at all**. Either alone is sufficient to rule out FULL."
    )


def _consequences(report: Any) -> str:
    """The downstream statistical consequences of the measured tier."""
    if report.fidelity == "FULL":
        return (
            "Repetitions are independent, so `evals/sequence_runner.py` may publish the Wilson "
            "interval it currently computes unconditionally at `:160`."
        )
    return (
        "- **The Wilson interval at `evals/sequence_runner.py:160` is not earned.** It is computed "
        "unconditionally today over k repetitions whose independence has now been measured and "
        "found absent. That is ISSUE-143, and this artifact is the evidence it needs.\n"
        "- **EVAL-P12.4 must withhold the CI** and print the order-effect check "
        "(`SEQUENCE_STATS_POLICY` §4: Cochran's Q across repetition indices, first-vs-last McNemar) "
        "as the primary statistic in its place. A run printing neither has reported nothing.\n"
        "- **PARTIAL is the correct and expected result here, not a failure of the measurement.** "
        "`reset_world` PATCHes `world_state.epoch` and `world_state.active_conditions` and nothing "
        "else (`evals/preconditions.py:84`) — no graph teardown, no `KNOWS_ABOUT` removal, no "
        "emotion store, no session cache. A FULL verdict from this code would have been the bug."
    )
